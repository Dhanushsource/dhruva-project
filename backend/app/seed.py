def seed_careers(database: Session) -> None:
    if database.query(Career).count():
        return
    for row in CAREERS:
        (
            name, domain, description, skills, subjects,
            duration, salary, demand, growth, eligibility,
        ) = row
        database.add(Career(
            name=name,
            domain=domain,
            description=description,
            required_skills=json.dumps(skills),
            preferred_subjects=json.dumps(subjects),
            education_duration=duration,
            salary_range=salary,
            market_demand=demand,
            growth_rate=growth,
            eligibility=eligibility,
        ))
    database.commit()
